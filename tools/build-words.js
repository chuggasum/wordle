// Builds ../words.js from answers.txt + allowed_extra.txt.
// Run: node tools/build-words.js
const fs = require('fs');
const path = require('path');

const read = f => fs.readFileSync(path.join(__dirname, f), 'utf8').toLowerCase().split(/\s+/).filter(Boolean);
const five = w => /^[a-z]{5}$/.test(w);

// Not suitable as answers (sensitive, plurals/odd forms, not everyday words)
const NOT_ANSWERS = new Set(('abuse death vodka tumor ulcer mucus naked toxic bible bikes drums dully humps hymns ' +
  'robes camps poems herbs myths dated tuned lived drawn boney pupal sylph gipsy mammal tuxedo cheddar ' +
  'ardor ashen bandy bylaw cairn chafe eerie elfin gecko ghoul lusty umbra unfit sable sassy zonal').split(' '));

// Removed everywhere: offensive for an ad-supported family game, proper nouns, non-words
const BLOCK = new Set(('sluts bitch dicks semen vulva pubic pubes busty whizz fanny hussy horny boner boobs cocks ' +
  'gypsy gipsy squaw japan swiss greek dutch welsh welch ralph sopra wases bider hoagy kests tared rifer pinga sputa ' +
  'viced shews wifes veges umped coked thens noway jiggy rands rials ikons unarm hades pigmy dural poops bombs ' +
  'jotted wases sirup fiscal aloha earl yoga yahoo yocks yogic yikes swede sluts nobby busty').split(' '));

const AU_EXTRA = 'bogan dunny ocker galah esky bonza smoko servo arvo stoked budgy drongo'.split(' ');

const clean = list => [...new Set(list.filter(five))].filter(w => !BLOCK.has(w));

const answers = clean(read('answers.txt')).filter(w => !NOT_ANSWERS.has(w) && !/[^sui]s$/.test(w))
  .filter(w => !BLOCK.has(w));
answers.push(...clean(['dingo', 'galah', 'bogan']).filter(w => !answers.includes(w)));

const allowed = clean([...read('allowed_extra.txt'), ...read('answers.txt'), ...AU_EXTRA, ...answers]);
const allowedSet = new Set(allowed);
answers.forEach(w => { if (!allowedSet.has(w)) throw new Error('answer not allowed: ' + w); });

// Deterministic shuffle so the daily order isn't alphabetical (mulberry32)
function rng(seed) { return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
const r = rng(20261020);
const order = answers.slice().sort();
for (let i = order.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [order[i], order[j]] = [order[j], order[i]]; }

const extra = allowed.filter(w => !order.includes(w)).sort();
const out = '// Generated by tools/build-words.js — do not edit by hand.\n' +
  'window.ANSWERS = ' + JSON.stringify(order.join(' ')) + '.split(" ");\n' +
  'window.EXTRA_GUESSES = ' + JSON.stringify(extra.join(' ')) + '.split(" ");\n';
fs.writeFileSync(path.join(__dirname, '..', 'words.js'), out);
console.log('answers:', order.length, ' valid guesses:', order.length + extra.length);
